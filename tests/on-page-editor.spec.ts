test('on-page edits can only change visible artwork/collection text, not metadata or hidden documents',()=>{
 const model:DocumentModel={portfolioSettings:{_id:'portfolioSettings',_type:'portfolioSettings',collections:[{_ref:'series'}]},series:{_id:'series',_type:'collection',title:'Series',artworks:[{_ref:'work'}]},work:{_id:'work',_type:'artwork',title:'Before',dimensions:'24 × 36'},hidden:{_id:'hidden',_type:'artwork',title:'Hidden'}}
 const changed=applyInlineEdits(model,[{id:'work',field:'title',value:'After'},{id:'work',field:'dimensions',value:'18 × 24'}])
 expect(changed.work.title).toBe('After');expect(model.work.title).toBe('Before')
 expect(()=>applyInlineEdits(model,[{id:'work',field:'_rev',value:'bad'}])).toThrow()
 expect(()=>applyInlineEdits(model,[{id:'hidden',field:'title',value:'bad'}])).toThrow()
})
test('clicking the actual webpage edits title and dimensions, flushes focused input, uploads images and publishes',async({page})=>{
 await page.setViewportSize({width:1440,height:1000})
 await page.goto('http://127.0.0.1:3333/tests/easy/?section=portfolio&visual=1')
 const frame=page.frameLocator('iframe')
 await expect(frame.locator('#content-status')).toContainText('Edit mode')
 await page.getByRole('button',{name:'Add collection',exact:true}).click()
 const category=frame.getByRole('textbox',{name:'Collection title',exact:true})
 await category.fill('Paintings');await category.press('Enter')
 const chooser=page.waitForEvent('filechooser')
 await frame.getByRole('button',{name:'Add artwork',exact:true}).click()
 await (await chooser).setFiles(image)
 await expect(frame.getByRole('textbox',{name:'Artwork title',exact:true})).toBeVisible()
 await frame.getByRole('textbox',{name:'Artwork title',exact:true}).fill('An edited painting')
 await frame.getByRole('textbox',{name:'Artwork title',exact:true}).press('Enter')
 const medium=frame.getByRole('textbox',{name:'Artwork medium',exact:true})
 await expect(medium).toHaveText('Oil on canvas')
 await medium.fill('Oil on panel');await medium.press('Enter')
 const dimensions=frame.getByRole('textbox',{name:'Artwork dimensions (inches by default)',exact:true})
 await dimensions.fill('18 × 24')
 // Save while the caret is still inside the frame; no manual blur or Enter.
 await page.getByRole('button',{name:'Save draft',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Draft saved')
 await page.getByRole('button',{name:'Use forms',exact:true}).click()
 await expect(page.getByRole('textbox',{name:'Dimensions (inches by default)',exact:true})).toHaveValue('18 × 24')
 await page.getByRole('button',{name:'Edit on page',exact:true}).click()
 await expect(frame.getByRole('textbox',{name:'Artwork dimensions (inches by default)',exact:true})).toBeVisible()
 await dimensions.fill('99 × 99');await dimensions.press('Escape')
 await expect(dimensions).toHaveText('18 × 24 in')
 const replace=page.waitForEvent('filechooser')
 await frame.getByRole('button',{name:/Change image for/}).click()
 await (await replace).setFiles({...image,name:'replacement.png'})
 await expect.poll(()=>page.evaluate(()=>Reflect.get(window,'editorTest').uploads)).toBe(2)
 await expect(frame.getByRole('dialog')).not.toBeVisible()
 await frame.getByRole('textbox',{name:'Artwork title',exact:true}).fill('Final painting title')
 await page.getByRole('button',{name:'Publish',exact:true}).click()
 await page.getByRole('button',{name:'Yes, publish Portfolio',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Portfolio published')
 expect(await page.evaluate(()=>Reflect.get(window,'editorTest').publishes)).toBe(1)
 await expect(frame.getByRole('textbox',{name:'Artwork title',exact:true})).toHaveText('Final painting title')
 await expect(medium).toHaveText('Oil on panel')
 await page.screenshot({path:'/tmp/hong-on-page-editor.png',fullPage:false})
})
